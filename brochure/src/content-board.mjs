const toBoardSeg = (s) => {
  const rank = { none: 0, half: 1, full: 2 };
  const best = (...v) => v.reduce((a, b) => (rank[b || "none"] > rank[a || "none"] ? b : a), "none");
  return { org: s.corp || "none", biz: best(s.comm, s.guild), retail: s.retail || "none" };
};

